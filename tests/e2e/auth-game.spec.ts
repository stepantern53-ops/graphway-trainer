import { test,expect } from '@playwright/test';
import { register,enterCredentials,currentProgress,newAccount } from './helpers';

test.use({trace:'off',screenshot:'off',video:'off',viewport:{width:1440,height:900}});
test.setTimeout(90_000);

test('auth L01 live incomplete theory menu frozen arrival retry reload and replay',async({page},testInfo)=>{
 await page.clock.install();
 const account=await register(page);
 await page.clock.pauseAt(new Date(Date.now()+2000));
 const field=page.locator('#coefficient-b');
 const launch=page.getByRole('button',{name:'▶ Пуск',exact:true});
 const graph=page.getByTestId('current-graph');
 const originalPath=await graph.getAttribute('d');
 const slider=page.getByRole('slider',{name:'Ползунок b'});
 await slider.focus();
 await page.keyboard.press('ArrowRight');
 await expect(field).toHaveValue('0.25');
 expect(await graph.getAttribute('d')).not.toBe(originalPath);
 for(const incomplete of ['-','1/','']){
  await field.fill(incomplete);
  await expect(graph).toHaveCount(0);
  await expect(launch).toBeDisabled();
 }
 for(const raw of ['-3/2','0,5']){
  await field.fill(raw);
  await expect(field).toHaveValue(raw);
  await expect(graph).toBeVisible();
  expect(await graph.getAttribute('d')).not.toBe(originalPath);
 }
 await field.fill('2');
 await expect(launch).toBeEnabled();
 await page.getByRole('button',{name:'Теория',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Линейная функция',exact:true})).toBeVisible();
 await expect(page.locator('.katex').first()).toBeVisible();
 await page.getByRole('button',{name:'Вернуться к графику'}).click();
 await expect(field).toHaveValue('2');
 const menuOpener=page.getByRole('button',{name:'☰ Меню трассы',exact:true});
 await menuOpener.focus();
 await page.keyboard.press('Enter');
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.keyboard.press('Escape');
 await expect(menuOpener).toBeFocused();
 await page.keyboard.press('Enter');
 await expect(page.getByRole('button',{name:'Продолжить',exact:true})).toBeFocused();
 await page.keyboard.press('Enter');
 await expect(menuOpener).toBeFocused();
 await expect(field).toHaveValue('2');
 expect(await page.evaluate(()=>({local:localStorage.length,session:sessionStorage.length,search:location.search}))).toEqual({local:0,session:0,search:''});
 const payloads:unknown[]=[];
 await page.route('**/api/levels/L01/complete',async route=>{
  payloads.push(route.request().postDataJSON());
  if(payloads.length===1)await route.abort('failed');else await route.continue();
 });
 await launch.click();
 await page.clock.runFor(500);
 await page.getByRole('button',{name:'☰ Меню трассы',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'На главную',exact:true}).click();
 await page.clock.runFor(4000);
 expect(payloads).toHaveLength(0);
 await page.getByRole('button',{name:'» Следующий уровень',exact:true}).click();
 await expect(field).toHaveValue('2');
 await expect(launch).toBeEnabled();
 await launch.click();
 await expect(field).toBeDisabled();
 expect(payloads).toHaveLength(0);
 await page.clock.runFor(700);
 const marker=await page.getByTestId('rider').getAttribute('transform');
 await page.getByRole('button',{name:'☰ Меню трассы',exact:true}).click();
 await page.clock.runFor(5000);
 expect(payloads).toHaveLength(0);
 await page.getByRole('button',{name:'Продолжить',exact:true}).click();
 expect(await page.getByTestId('rider').getAttribute('transform')).toBe(marker);
 await page.getByRole('button',{name:'Теория',exact:true}).click();
 await page.clock.runFor(5000);
 expect(payloads).toHaveLength(0);
 await page.getByRole('button',{name:'Вернуться к графику'}).click();
 await page.clock.runFor(3000);
 await expect(page.getByTestId('route-status')).toContainText('прохождение не подтверждено');
 expect((await currentProgress(page)).completedLevelIds).not.toContain('L01');
 await expect(field).toHaveValue('2');
 const arrived=await page.getByTestId('rider').getAttribute('transform');
 await page.getByRole('button',{name:'Повторить сохранение',exact:true}).click();
 await expect(page.getByTestId('route-status')).toContainText('Прохождение подтверждено сервером');
 expect(payloads).toEqual([{curriculumVersion:'graphway-v1',coefficients:{b:'2'}},{curriculumVersion:'graphway-v1',coefficients:{b:'2'}}]);
 expect(await page.getByTestId('rider').getAttribute('transform')).toBe(arrived);
 expect((await currentProgress(page)).unlockedLevelIds).toEqual(['L01','L02']);
 await page.screenshot({path:testInfo.outputPath('L01-confirmed-desktop.png'),fullPage:true});
 await page.reload();
 await expect(field).toHaveValue('0');
 await expect(launch).toBeDisabled();
 await page.clock.runFor(6000);
 expect(payloads).toHaveLength(2);
 expect((await currentProgress(page)).completedCount).toBe(1);
 await page.goto('/#/levels/L02');
 await expect(field).toHaveValue('1');
 await page.getByRole('button',{name:/^◎ /}).click();
 await page.getByRole('button',{name:'Выйти из аккаунта',exact:true}).click();
 await page.getByRole('button',{name:'Вход',exact:true}).click();
 await enterCredentials(page,account);
 await page.getByRole('button',{name:'Войти и продолжить →'}).click();
 await expect(page).toHaveURL(/#\/levels\/L02$/);
 await expect(field).toHaveValue('1');
 expect((await currentProgress(page)).completedLevelIds).toEqual(['L01']);
 await page.goto('/#/levels/L01');
 await expect(field).toHaveValue('0');
 await field.fill('2');
 await page.context().clearCookies();
 await launch.click();
 await page.clock.runFor(3200);
 await expect(page.getByRole('heading',{name:'Сессия завершилась',exact:true})).toBeVisible();
 await enterCredentials(page,account);
 await page.getByRole('button',{name:'Войти и продолжить →'}).click();
 await expect(field).toHaveValue('2');
 await expect(page.getByRole('button',{name:'Повторить сохранение',exact:true})).toBeVisible();
 const beforeRetry=await page.getByTestId('rider').getAttribute('transform');
 await page.getByRole('button',{name:'Повторить сохранение',exact:true}).click();
 await expect(page.getByTestId('route-status')).toContainText('Прохождение подтверждено сервером');
 expect(await page.getByTestId('rider').getAttribute('transform')).toBe(beforeRetry);
 expect((await currentProgress(page)).completedCount).toBe(1);
 expect(payloads.slice(-2)).toEqual([{curriculumVersion:'graphway-v1',coefficients:{b:'2'}},{curriculumVersion:'graphway-v1',coefficients:{b:'2'}}]);
 await page.context().clearCookies();
 await page.getByRole('button',{name:'GraphWay - главная',exact:true}).click();
 // Home reads the real catalog immediately, so its 401 shows authentication without a stale catalog click.
 await expect(page.getByRole('heading',{name:'Сессия завершилась',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Регистрация',exact:true}).click();
 await enterCredentials(page,newAccount());
 await page.getByRole('button',{name:'Создать аккаунт и открыть L01 →'}).click();
 await expect(page).toHaveURL(/#\/levels\/L01$/);
 await expect(field).toHaveValue('0');
 await expect(launch).toBeDisabled();
 expect((await currentProgress(page)).completedCount).toBe(0);
 await field.fill('2');
 await page.context().clearCookies();
 await page.getByRole('button',{name:/^◎ /}).click();
 await page.getByRole('button',{name:'Выйти из аккаунта',exact:true}).click();
 await expect(page.locator('#password')).toBeVisible();
 await expect(field).toHaveCount(0);
});
